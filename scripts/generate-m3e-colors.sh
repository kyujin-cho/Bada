#!/usr/bin/env bash
#
# Regenerates the Material 3 Expressive color scheme of Theme.Bada.Expressive:
#   app/src/main/res/values/colors_m3e.xml        (light)
#   app/src/main/res/values-night/colors_m3e.xml  (dark)
#
# Scheme: @material/material-color-utilities 0.4.0, SchemeVibrant, spec 2025,
# platform phone, contrast 0, seeded from the brand blue (brand_primary).
# Needs node and npm; installs the pinned package into a temp directory.

set -euo pipefail

ROOT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
SEED="${1:-0xFF0F62FE}"
WORK_DIR=$(mktemp -d)
trap 'rm -rf "$WORK_DIR"' EXIT

cd "$WORK_DIR"
npm init -y >/dev/null
npm install --silent @material/material-color-utilities@0.4.0

# The package ships extensionless ESM imports; resolve them as .js.
cat > loader.mjs <<'JS'
export async function resolve(specifier, context, next) {
  try {
    return await next(specifier, context);
  } catch (error) {
    if (!specifier.startsWith('.')) throw error;
    return next(specifier + '.js', context);
  }
}
JS
cat > register.mjs <<'JS'
import { register } from 'node:module';
import { pathToFileURL } from 'node:url';
register('./loader.mjs', pathToFileURL('./'));
JS

cat > generate.mjs <<'JS'
import * as m from '@material/material-color-utilities';
import fs from 'node:fs';

const [seedArg, resDir] = process.argv.slice(2);
const seed = m.Hct.fromInt(Number(seedArg));
const hex = (argb) => '#FF' + (argb >>> 0).toString(16).padStart(8, '0').slice(2).toUpperCase();
// [resource name suffix, MaterialDynamicColors key]
const roles = [
  ['primary', 'primary'], ['on_primary', 'onPrimary'], ['primary_container', 'primaryContainer'],
  ['on_primary_container', 'onPrimaryContainer'], ['primary_inverse', 'inversePrimary'],
  ['primary_fixed', 'primaryFixed'], ['primary_fixed_dim', 'primaryFixedDim'],
  ['on_primary_fixed', 'onPrimaryFixed'], ['on_primary_fixed_variant', 'onPrimaryFixedVariant'],
  ['secondary', 'secondary'], ['on_secondary', 'onSecondary'], ['secondary_container', 'secondaryContainer'],
  ['on_secondary_container', 'onSecondaryContainer'], ['secondary_fixed', 'secondaryFixed'],
  ['secondary_fixed_dim', 'secondaryFixedDim'], ['on_secondary_fixed', 'onSecondaryFixed'],
  ['on_secondary_fixed_variant', 'onSecondaryFixedVariant'],
  ['tertiary', 'tertiary'], ['on_tertiary', 'onTertiary'], ['tertiary_container', 'tertiaryContainer'],
  ['on_tertiary_container', 'onTertiaryContainer'], ['tertiary_fixed', 'tertiaryFixed'],
  ['tertiary_fixed_dim', 'tertiaryFixedDim'], ['on_tertiary_fixed', 'onTertiaryFixed'],
  ['on_tertiary_fixed_variant', 'onTertiaryFixedVariant'],
  ['error', 'error'], ['on_error', 'onError'], ['error_container', 'errorContainer'],
  ['on_error_container', 'onErrorContainer'],
  ['background', 'background'], ['on_background', 'onBackground'],
  ['surface', 'surface'], ['on_surface', 'onSurface'], ['surface_variant', 'surfaceVariant'],
  ['on_surface_variant', 'onSurfaceVariant'], ['surface_inverse', 'inverseSurface'],
  ['on_surface_inverse', 'inverseOnSurface'], ['surface_bright', 'surfaceBright'], ['surface_dim', 'surfaceDim'],
  ['surface_container_lowest', 'surfaceContainerLowest'], ['surface_container_low', 'surfaceContainerLow'],
  ['surface_container', 'surfaceContainer'], ['surface_container_high', 'surfaceContainerHigh'],
  ['surface_container_highest', 'surfaceContainerHighest'],
  ['outline', 'outline'], ['outline_variant', 'outlineVariant'],
];
const header = `Material 3 Expressive color scheme for Theme.Bada.Expressive.

  GENERATED by scripts/generate-m3e-colors.sh. Do not edit by hand.
  @material/material-color-utilities 0.4.0: SchemeVibrant, spec version
  2025, platform phone, contrast 0, seeded from the brand blue #0F62FE
  (brand_primary / the launcher icon). M3 Expressive asks for vibrant
  schemes that "sharpen hierarchy and clarify key actions"; the Vibrant
  variant keeps the primary close to the brand blue, which Tonal Spot
  mutes to a gray-blue.`;
for (const dark of [false, true]) {
  const scheme = new m.SchemeVibrant(seed, dark, 0, '2025', 'phone');
  const mode = dark
    ? 'Night (dark) values. values/colors_m3e.xml holds the light scheme.'
    : 'Day (light) values. values-night/colors_m3e.xml holds the dark scheme.';
  let xml = `<?xml version="1.0" encoding="utf-8"?>\n<!--\n  ${header}\n\n  ${mode}\n-->\n<resources>\n`;
  for (const [name, key] of roles) {
    xml += `    <color name="m3e_${name}">${hex(m.MaterialDynamicColors[key].getArgb(scheme))}</color>\n`;
  }
  // Static colors (M3 "static colors": one reference color, four roles) for the
  // permission-status text. Not harmonized: success and warning must read the
  // same everywhere. Only the main role is emitted; it is the text-on-surface tone.
  for (const [name, argb] of [['success', 0xFF2E7D32], ['warning', 0xFFE65100]]) {
    const palette = m.TonalPalette.fromInt(argb);
    xml += `    <color name="m3e_${name}">${hex(palette.tone(dark ? 80 : 40))}</color>\n`;
  }
  xml += '</resources>\n';
  fs.writeFileSync(`${resDir}/${dark ? 'values-night' : 'values'}/colors_m3e.xml`, xml);
}
JS

node --import ./register.mjs generate.mjs "$SEED" "$ROOT_DIR/app/src/main/res"
echo "Wrote colors_m3e.xml (light + night) from seed $SEED"
